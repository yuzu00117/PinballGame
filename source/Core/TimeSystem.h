//------------------------------------------------------------------------------
// TimeSystem
//------------------------------------------------------------------------------
// 役割:
// ゲーム全体の時間管理を行う静的クラス。
// 高精度タイマを用いてフレーム間の経過時間を計測し、
// ゲーム時間（TimeScale考慮）と実時間を提供する。
//
// 設計意図:
// ゲームループから独立した時間管理を行うことで、
// スローモーション・停止・演出用の時間制御を容易にする。
// static クラスとして実装し、グローバルに参照可能とする。
//
// 構成:
// - 高精度タイマ（QueryPerformanceCounter）
// - DeltaTime（TimeScale考慮）
// - UnscaledDeltaTime（実時間）
// - TimeScale による時間制御
//
// NOTE:
// TimeSystem 自体は状態を持つが、明示的なインスタンス生成は行わない。
// Init() はアプリケーション起動時に一度だけ呼び出すこと。
//------------------------------------------------------------------------------
#pragma once

#ifndef NOMINMAX
#define NOMINMAX
#endif

// 標準ライブラリ
#include <windows.h>

class TimeSystem
{
public:
    // ----------------------------------------------------------------------
    // ライフサイクルメソッド
    // ----------------------------------------------------------------------
    /// 初期化処理
    /// - 高精度タイマの周波数と初期カウンタ値を取得する
    static void Init();

    /// 更新処理
    /// - 前フレームからの経過時間を計測する
    /// - DeltaTime / UnscaledDeltaTime を更新する
    static void Update();

    // ----------------------------------------------------------------------
    // 経過秒取得
    // ----------------------------------------------------------------------
    /// 経過秒を取得する（TimeScale考慮）
    /// - ゲーム進行に使用する時間
    static float DeltaTime();         // 秒

    /// 経過秒を取得する（TimeScale無視）
    /// - 一時停止中も動かしたい処理に使用する
    static float UnscaledDeltaTime(); // 秒

    // ----------------------------------------------------------------------
    // 時間制御
    // ----------------------------------------------------------------------
    /// 時間の進み具合を設定する
    /// - 1.0f : 通常速度
    /// - 0.5f : 半分の速度
    /// - 2.0f : 2倍速
    /// - 0.0f : 停止
    static void SetTimeScale(float scale);

    /// 時間の進み具合を取得する
    static float TimeScale();

private:
    // ----------------------------------------------------------------------
    // 内部状態
    // ----------------------------------------------------------------------
    static LARGE_INTEGER s_Freq;          // 高精度タイマの周波数
    static LARGE_INTEGER s_Prev;          // 前フレームのカウンタ値
    static float s_UnscaledDelta;         // 経過秒（TimeScale無視）
    static float s_Delta;                 // 経過秒（TimeScale考慮）
    static float s_TimeScale;             // 時間の進み具合
};
