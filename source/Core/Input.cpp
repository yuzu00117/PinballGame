#include "main.h"
#include "input.h"

//------------------------------------------------------------------------------
// 静的メンバ変数
//------------------------------------------------------------------------------
BYTE Input::m_OldKeyState[256];
BYTE Input::m_KeyState[256];

//------------------------------------------------------------------------------
// 初期化処理
//------------------------------------------------------------------------------
/// 入力システム初期化
/// - 現在 / 前フレームのキー状態をすべて「未入力」に初期化する
void Input::Init()
{
    // 両バッファを「未入力」で初期化
    memset(m_OldKeyState, 0, 256);
    memset(m_KeyState, 0, 256);
}

//------------------------------------------------------------------------------
// 終了処理
//------------------------------------------------------------------------------
/// 終了処理
/// NOTE:
/// - 現在は明示的な解放処理は存在しない
void Input::Uninit()
{
}

//------------------------------------------------------------------------------
// 更新処理
//------------------------------------------------------------------------------
/// 入力状態更新
/// - 現在のキー状態を前フレーム用バッファへ退避
/// - Windows API から最新のキー状態を取得
void Input::Update()
{
    // 現在の状態を前フレーム用に保存
    memcpy(m_OldKeyState, m_KeyState, 256);

    // 最新のキーボード状態を取得
    GetKeyboardState(m_KeyState);
}

//------------------------------------------------------------------------------
// 入力取得
//------------------------------------------------------------------------------
/// キーが押されているかを取得
/// @param KeyCode 仮想キーコード（VK_XXX）
/// @return 押されている間 true
bool Input::GetKeyPress(BYTE KeyCode)
{
    // 上位ビットが 1 の場合、キーが押下されている
    return (m_KeyState[KeyCode] & 0x80) != 0;
}

/// キーが押された瞬間かを取得
/// @param KeyCode 仮想キーコード（VK_XXX）
/// @return 押された瞬間のフレームのみ true
bool Input::GetKeyTrigger(BYTE KeyCode)
{
    // 現在フレームで押されており、前フレームでは押されていない
    return ( (m_KeyState[KeyCode] & 0x80) &&
            !(m_OldKeyState[KeyCode] & 0x80) );
}
