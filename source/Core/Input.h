//------------------------------------------------------------------------------
// Input
//------------------------------------------------------------------------------
// 役割:
// キーボード入力を管理する静的クラス。
// Windows の仮想キーコード（BYTE）を用いて、
// 「押されているか」「押された瞬間か」を判定する。
//
// 設計意図:
// フレーム単位で現在・前フレームのキー状態を保持し、
// トリガー入力（押した瞬間）を簡潔に取得できるようにする。
// インスタンス化を行わず、システム全体から参照可能な
// ユーティリティとして実装している。
//
// 構成:
// - 現在フレームのキー状態   : m_KeyState
// - 前フレームのキー状態     : m_OldKeyState
// - ライフサイクル           : Init / Update
//
// NOTE:
// - 内部で GetKeyboardState を使用しているため、
//   Windows API に依存する実装となっている。
//------------------------------------------------------------------------------
#pragma once

class Input
{
private:
    // ----------------------------------------------------------------------
    // 内部状態
    // ----------------------------------------------------------------------
    static BYTE m_OldKeyState[256];   // 前フレームのキー状態（仮想キー256種）
    static BYTE m_KeyState[256];      // 現在フレームのキー状態

public:
    // ----------------------------------------------------------------------
    // ライフサイクル
    // ----------------------------------------------------------------------
    /// 入力システム初期化
    static void Init();

    /// 終了処理（将来拡張用）
    static void Uninit();

    /// 毎フレーム呼び出す更新処理
    static void Update();

    // ----------------------------------------------------------------------
    // 入力取得
    // ----------------------------------------------------------------------
    /// キーが押されている間 true
    static bool GetKeyPress(BYTE KeyCode);

    /// キーが押された瞬間のみ true
    static bool GetKeyTrigger(BYTE KeyCode);
};
