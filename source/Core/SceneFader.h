//------------------------------------------------------------------------------
// SceneFader
//------------------------------------------------------------------------------
// 役割:
// 画面遷移時のフェードアウト→フェードイン演出を管理するシングルトンクラス。
// 全画面を覆う黒スプライトのアルファ値をイージング関数で変化させる。
//
// 設計意図:
// フェードの状態（Idle / FadeOut / FadeIn）をステートマシンで管理し、
// GameManager の ChangeScene() と分離することで遷移ロジックを単純化する。
// シーン切り替えのタイミングはフェードアウト完了時のコールバックで実行する。
//
// 構成:
// - Init()       : 黒オーバーレイスプライトを生成する
// - Uninit()     : スプライトを解放する
// - BeginFade()  : フェード開始（コールバックと継続時間を受け取る）
// - Update()     : 状態更新・アルファ値変化
// - Draw()       : 黒オーバーレイの描画
// - IsFading()   : フェード中かどうかの判定
//
// NOTE:
// GameManager::Init() 内で SceneFader::Init() を呼ぶこと。
// Sprite リソースを内部で保持するため、Renderer 初期化後に Init() すること。
// Draw() は全シーン描画の最後に呼ぶこと（最前面に描画するため）。
//------------------------------------------------------------------------------
#pragma once

#include <functional>

class Sprite;

/// 画面遷移フェードを管理するクラス
/// - BeginFade() でフェードアウト開始、完了時にコールバックが呼ばれる
/// - コールバック後フェードインが始まり、完了すると Idle に戻る
class SceneFader
{
public:
    // ------------------------------------------------------------------
    // ライフサイクル
    // ------------------------------------------------------------------

    /// 初期化処理（黒オーバーレイスプライトを生成する）
    /// - NOTE: Renderer 初期化後に呼ぶこと
    static void Init();

    /// 終了処理（スプライトを解放する）
    static void Uninit();

    // ------------------------------------------------------------------
    // フェード制御
    // ------------------------------------------------------------------

    /// フェードアウト→コールバック実行→フェードインを開始する
    /// - onMidpoint : フェードアウト完了時（画面が完全に黒い瞬間）に呼ばれるコールバック
    /// - duration   : フェードアウト・フェードイン それぞれの時間（秒）
    /// - NOTE: 既にフェード中の場合は何もしない
    static void BeginFade(std::function<void()> onMidpoint, float duration = 0.5f);

    /// 毎フレーム状態を更新する
    static void Update(float deltaTime);

    /// 黒オーバーレイを描画する
    /// - NOTE: 全シーン描画の最後に呼ぶこと
    static void Draw();

    /// フェードアニメーション中かどうかを返す
    /// - true : FadeOut / FadeIn 中
    /// - false: Idle 状態
    static bool IsFading();

private:
    /// フェード状態
    enum class State
    {
        Idle,    // フェードなし（通常状態）
        FadeOut, // フェードアウト中（alpha: 0 → 1）
        FadeIn,  // フェードイン中（alpha: 1 → 0）
    };

    // ------------------------------------------------------------------
    // メンバ変数
    // ------------------------------------------------------------------
    static State                 m_State;      // 現在のフェード状態
    static float                 m_Timer;      // 現フェーズの経過時間（秒）
    static float                 m_Duration;   // 1フェーズの継続時間（秒）
    static float                 m_Alpha;      // オーバーレイのアルファ値 [0.0, 1.0]
    static std::function<void()> m_OnMidpoint; // 所有：フェードアウト完了時コールバック
    static Sprite*               m_Overlay;    // 所有：黒オーバーレイスプライト
};
