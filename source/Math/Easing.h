//------------------------------------------------------------------------------
// Easing
//------------------------------------------------------------------------------
// 役割:
// イージング関数群を提供するヘッダーオンリーユーティリティ。
// t = 0.0?1.0 の正規化時間を受け取り、変換後の値を返す。
//
// 設計意図:
// 画面遷移のフェード・UI演出など、アニメーション補間に再利用できるよう
// シンプルな純粋関数として切り出す。GameManager や個別シーンから参照する。
//
// 構成:
// - EaseInQuad    : 二次関数によるイーズイン（加速）
// - EaseOutQuad   : 二次関数によるイーズアウト（減速）
// - EaseInOutQuad : 二次関数によるイーズイン/アウト（前半加速・後半減速）
//
// NOTE:
// t は [0.0, 1.0] の範囲で渡すこと。範囲外は未定義動作。
// テンプレートではなく float 固定とする（GPU 演算との混在を避けるため）。
//------------------------------------------------------------------------------
#pragma once

/// 二次関数によるイーズイン（加速）
/// - t=0 で 0.0、t=1 で 1.0 を返す
/// - 副作用：なし
inline float EaseInQuad(float t)
{
    return t * t;
}

/// 二次関数によるイーズアウト（減速）
/// - t=0 で 0.0、t=1 で 1.0 を返す
/// - 副作用：なし
inline float EaseOutQuad(float t)
{
    return t * (2.0f - t);
}

/// 二次関数によるイーズイン/アウト（前半加速・後半減速）
/// - t=0 で 0.0、t=0.5 で 0.5、t=1 で 1.0 を返す
/// - 副作用：なし
inline float EaseInOutQuad(float t)
{
    return (t < 0.5f) ? 2.0f * t * t : -1.0f + (4.0f - 2.0f * t) * t;
}
