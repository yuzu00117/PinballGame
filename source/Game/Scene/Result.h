//------------------------------------------------------------------------------
// Result.h
//------------------------------------------------------------------------------
// 役割:
// リザルト画面を表示するためのシーン用 GameObject。
// 描画（テキスト/背景など）を行い、必要に応じて入力を監視して遷移させる。
//
// 設計意図:
// Result は「シーン上の表示担当」として GameObject のライフサイクルに乗せる。
// 背景画像の描画は Sprite クラスに委譲し、Result 自身は D3D リソースを保持しない。
//
// 構成:
// - ライフサイクル         : Init / Uninit / Update / Draw
// - 背景描画               : Sprite による TitleBackGround.png の全画面描画
// - テキスト描画           : Renderer::DrawText によるリザルト文字・操作案内
//------------------------------------------------------------------------------
#pragma once

#include "GameObject.h"
#include "Sprite.h"

/// リザルト画面を表示するシーン用オブジェクト
/// - Draw でリザルト表示を描画する
/// - Update で入力を監視し、必要に応じてシーン遷移する想定
class Result : public GameObject
{
public:
	//------------------------------------------------------------------------------
	// ライフサイクルメソッド
	//------------------------------------------------------------------------------
	/// 初期化処理
	/// - 必要な描画リソースを生成する（現状は未実装）
	void Init() override;

	/// 終了処理
	/// - 生成した描画リソースを解放する（現状は未実装）
	void Uninit() override;

	/// 更新処理（deltaTime は秒単位）
	/// - 入力監視や状態更新を行う（現状は未実装）
	void Update(float deltaTime) override;

	/// 描画処理
	/// - リザルト表示テキストを描画する
	void Draw() override;

private:
	//------------------------------------------------------------------------------
	// テキストの描画位置
	//------------------------------------------------------------------------------
	static constexpr int kResultX = 100;
	static constexpr int kResultY = 200;
	static constexpr int kPromptX = 100;
	static constexpr int kPromptY = 280;

	//------------------------------------------------------------------------------
	// テクスチャのファイルパス
	//------------------------------------------------------------------------------
	static constexpr const wchar_t* kBgPath = L"asset\\texture\\TitleBackGround.png";

	//------------------------------------------------------------------------------
	// 子オブジェクト
	//------------------------------------------------------------------------------
	Sprite* m_BgSprite = nullptr; // 非所有：GameObjectの子として管理
};
