//------------------------------------------------------------------------------
// SpriteSheet.h
//------------------------------------------------------------------------------
// 役割:
// スプライトシート（1枚の画像に複数のコマが並んだもの）の描画を行うクラス。
// Sprite クラスを継承し、インデックス指定による特定コマの切り出し表示をサポートする。
//
// 設計意図:
// 画像の分割数（行・列）を設定し、描画したいコマのインデックスを指定することで
// 自動的に UV 座標を算出して描画する機能を提供する。
// 数値フォントやアニメーション用のコマ画像など、汎用的に利用可能。
//
// 構成:
// - SetGrid        : スプライトシートの分割数（列・行）を指定
// - SetIndex       : 描画するコマのインデックス（0～）を指定
// - Sprite の機能  : SetPosition、SetSize 等の表示系メソッドを継承
//
// NOTE:
// 継承元の Sprite::Draw() を使用する。
// インデックスは 0 から始まり、左上から右へ、端に達したら下の行へ進む順序とする。
//------------------------------------------------------------------------------
#pragma once

#include "Sprite.h"

/// スプライトシート描画用クラス
/// - 指定された分割数に基づき、インデックスで画像の一部を切り出して表示する
class SpriteSheet : public Sprite
{
public:
    //------------------------------------------------------------------------------
    // ライフサイクルメソッド
    //------------------------------------------------------------------------------
    /// 初期化処理
    void Init() override;

    /// 終了処理
    void Uninit() override;

    /// 描画処理
    /// - 内部で UV 座標を再計算してから Sprite::Draw() を呼び出す
    void Draw() override;

    //------------------------------------------------------------------------------
    // スプライトシート設定
    //------------------------------------------------------------------------------
    /// 画像の分割数を設定する（等分割用）
    /// @param cols 横方向の分割数（列数）
    /// @param rows 縦方向の分割数（行数）
    void SetGrid(int cols, int rows);

    /// ピクセル単位で直接UV座標を設定する
    /// - 等分割ではどうしてもズレるような、不規則なスプライトシートに対応する
    /// @param x 左上のX座標（ピクセル）
    /// @param y 左上のY座標（ピクセル）
    /// @param width 切り抜く幅（ピクセル）
    /// @param height 切り抜く高さ（ピクセル）
    /// @param texWidth テクスチャ全体の幅（ピクセル）
    /// @param texHeight テクスチャ全体の高さ（ピクセル）
    void SetUVRect(float x, float y, float width, float height, float texWidth, float texHeight);

    /// 表示するコマのインデックスを設定する（等分割モード用）
    /// - 0 から始まり、横方向（右）に進み、端で次の行へ進む順番
    /// @param index 表示するコマの番号
    void SetIndex(int index);

private:
    //------------------------------------------------------------------------------
    // スプライトシート管理 / 計算処理
    //------------------------------------------------------------------------------
    /// 現在の分割数とインデックスから UV 座標を計算し設定する（等分割用）
    void UpdateGridUV();

    int  m_Columns = 1; // 列数（横の分割数）
    int  m_Rows    = 1; // 行数（縦の分割数）
    int  m_Index   = 0; // 現在表示中のコマのインデックス
    bool m_IsGridMode = true; // SetGridによる自動分割モードか、直接指定（SetUVRect）モードか
};
